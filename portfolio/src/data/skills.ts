export interface SkillEvidence {
  projectSlug: string;
  label?: string;
}

export interface SkillItem {
  /**
   * Stable invariant technical identifier across all locales.
   * e.g. "python", "typescript", "mcp", "pytorch".
   */
  id: string;

  /**
   * Localized display name.
   */
  name: string;

  icon?: string;
  note?: string;

  /**
   * 1 = exploring, 2 = foundations, 3 = operational,
   * 4 = proficient, 5 = autonomous delivery (design, debug, deliver).
   */
  proficiency?: 1 | 2 | 3 | 4 | 5;

  /**
   * True for key focus areas / specialties to prioritize.
   */
  focus?: boolean;

  /**
   * Verifiable contexts of practice.
   */
  contexts?: SkillContext[];

  /**
   * Links to project proofs on /projects.
   */
  evidence?: SkillEvidence[];
}

